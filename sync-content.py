#!/usr/bin/env python3
"""Refresh the offline snapshot used when index.html is opened directly."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
OUTPUT = ROOT / "assets" / "js" / "content-fallback.js"

content = {
    "news": (DATA / "news.txt").read_text(encoding="utf-8"),
    "papers": (DATA / "papers.txt").read_text(encoding="utf-8"),
}

for name, text in content.items():
    if len(text) > 1_000_000:
        raise ValueError(f"{name}.txt exceeds the 1 MB content limit.")

serialized = json.dumps(content, ensure_ascii=False, separators=(",", ":"))
OUTPUT.write_text(
    "// Generated by sync-content.py. Edit data/news.txt or data/papers.txt instead.\n"
    f"window.__SITE_CONTENT__ = {serialized};\n",
    encoding="utf-8",
)
print(f"Updated {OUTPUT.relative_to(ROOT)}")
